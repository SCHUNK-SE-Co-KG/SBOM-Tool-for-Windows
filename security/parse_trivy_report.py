#!/usr/bin/env python3
"""Convert Trivy JSON output to Markdown summary for security/reports/."""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORT_DIR = ROOT / "security" / "reports"


def parse_trivy(path: Path) -> str:
    data = json.loads(path.read_text(encoding="utf-8"))
    lines = [
        "# Trivy Scan Report – SBOM Tool for Windows",
        "",
        f"**Generated:** {datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}",
        f"**Source:** `{path.name}`",
        "",
    ]
    total = 0
    high_crit: list[str] = []
    for result in data.get("Results") or []:
        target = result.get("Target", "unknown")
        vulns = result.get("Vulnerabilities") or []
        total += len(vulns)
        lines.extend([f"## {target}", ""])
        if not vulns:
            lines.append("_No vulnerabilities._")
            lines.append("")
            continue
        lines.extend(["| ID | Severity | Package | Installed | Fixed |", "|----|----------|---------|-----------|-------|"])
        for v in vulns:
            sev = (v.get("Severity") or "UNKNOWN").upper()
            vid = v.get("VulnerabilityID", "?")
            pkg = v.get("PkgName", "?")
            installed = v.get("InstalledVersion", "-")
            fixed = v.get("FixedVersion") or "-"
            lines.append(f"| {vid} | {sev} | {pkg} | {installed} | {fixed} |")
            if sev in ("CRITICAL", "HIGH"):
                high_crit.append(f"{vid} ({sev}) in {pkg}@{installed}")
        lines.append("")
    lines.insert(4, f"**Total findings:** {total}")
    lines.insert(5, f"**High/Critical:** {len(high_crit)}")
    lines.append("---")
    lines.append("*Generated by `security/parse_trivy_report.py`*")
    return "\n".join(lines)


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else REPORT_DIR / "trivy-report.json"
    if not src.exists():
        sys.exit(f"Trivy report not found: {src}")
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    md = parse_trivy(src)
    (REPORT_DIR / "trivy_report.md").write_text(md, encoding="utf-8")
    print(f"Wrote {REPORT_DIR / 'trivy_report.md'}")


if __name__ == "__main__":
    main()
